class RateLimiter:
    """Sliding-window rate limiter"""
    def __init__(self, max_calls: int = RATE_LIMIT_CALLS, window: int = RATE_LIMIT_WINDOW):
        self.max_calls = max_calls
        self.window = window
        self.calls = []

    def check_limit(self) -> bool:
        now = time.time()
        self.calls = [t for t in self.calls if now - t < self.window]
        if len(self.calls) >= self.max_calls:
            return False
        self.calls.append(now)
        return True

    def time_until_reset(self) -> int:
        if not self.calls:
            return 0
        return max(0, int(self.window - (time.time() - self.calls[0])))


class DockerManager:
    """Manages Docker Desktop and LucidLink container"""

    def __init__(self):
        self.client = None

    def is_docker_installed(self) -> bool:
        return os.path.exists('/Applications/Docker.app')

    def is_docker_running(self) -> bool:
        try:
            self.client = docker.from_env()
            self.client.ping()
            return True
        except Exception as e:
            logger.debug(f"Docker not running: {e}")
            return False

    def start_docker(self) -> bool:
        if not self.is_docker_installed():
            return False
        if self.is_docker_running():
            return True
        try:
            logger.info("Starting Docker Desktop...")
            subprocess.run(['open', '-a', 'Docker'], check=True)
            for i in range(DOCKER_TIMEOUT):
                if self.is_docker_running():
                    logger.info("Docker Desktop started successfully")
                    return True
                time.sleep(1)
            logger.error("Docker Desktop failed to start within timeout")
            return False
        except subprocess.CalledProcessError as e:
            logger.error(f"Failed to start Docker Desktop: {e}")
            return False

    def image_exists(self, image_name: str) -> bool:
        if not self.is_docker_running():
            if not self.start_docker():
                return False
        try:
            self.client.images.get(image_name)
            return True
        except docker.errors.ImageNotFound:
            return False
        except Exception as e:
            logger.error(f"Error checking for image: {e}")
            return False

    def pull_image(self, image_name: str) -> tuple[bool, str]:
        if not self.is_docker_running():
            if not self.start_docker():
                return False, "Docker is not running and failed to start"
        try:
            logger.info(f"Pulling image {image_name} from Docker Hub...")
            self.client.images.pull(image_name)
            return True, f"Successfully pulled image: {image_name}"
        except docker.errors.APIError as e:
            logger.error(f"Failed to pull image: {e}")
            return False, f"Failed to pull image from Docker Hub: {str(e)}"
        except Exception as e:
            logger.error(f"Unexpected error pulling image: {e}")
            return False, f"Unexpected error: {str(e)}"

    def ensure_container_running(self, image_name: str = CONTAINER_IMAGE,
                                 container_name: str = CONTAINER_NAME) -> tuple[Optional[docker.models.containers.Container], Optional[str]]:
        if not self.is_docker_running():
            if not self.start_docker():
                return None, "Docker Desktop is not running and failed to start"
        try:
            container = self.client.containers.get(container_name)
            if container.status != 'running':
                logger.info(f"Starting existing container {container_name}")
                container.start()
                time.sleep(2)
            return container, None
        except docker.errors.NotFound:
            if not self.image_exists(image_name):
                logger.info(f"Image {image_name} not found locally, attempting to pull...")
                success, message = self.pull_image(image_name)
                if not success:
                    return None, (
                        f"Container image '{image_name}' not found locally and failed to pull. "
                        f"Error: {message}"
                    )
            try:
                container = self.client.containers.run(
                    image_name,
                    detach=True,
                    name=container_name,
                    ports={'3003/tcp': 3003},
                    restart_policy={"Name": "unless-stopped"}
                )
                time.sleep(3)
                return container, None
            except docker.errors.APIError as e:
                logger.error(f"Failed to create container: {e}")
                return None, f"Failed to create container: {str(e)}"
        except Exception as e:
            return None, f"Unexpected error: {str(e)}"

    def get_container_logs(self, lines: int = 50) -> str:
        try:
            container = self.client.containers.get(CONTAINER_NAME)
            return container.logs(tail=lines, decode=True)
        except Exception as e:
            return f"Error getting logs: {e}"

    def stop_container(self) -> bool:
        try:
            container = self.client.containers.get(CONTAINER_NAME)
            container.stop()
            return True
        except Exception:
            return False


class LucidLinkAPIClient:
    """Client for LucidLink Connect API operations"""

    def __init__(self, bearer_token: str, base_url: str = API_BASE_URL):
        self.base_url = base_url
        self.bearer_token = bearer_token
        self.headers = {
            "Authorization": f"Bearer {bearer_token}",
            "Content-Type": "application/json"
        }
        self.rate_limiter = RateLimiter()

    def _make_request(self, method: str, endpoint: str,
                      data: Optional[Dict] = None,
                      params: Optional[Dict] = None) -> ApiResponse:
        if not self.rate_limiter.check_limit():
            wait_time = self.rate_limiter.time_until_reset()
            return ApiResponse(
                success=False,
                error=f"Rate limit exceeded. Please wait {wait_time} seconds."
            )
        url = f"{self.base_url}{endpoint}"
        try:
            response = requests.request(
                method=method,
                url=url,
                headers=self.headers,
                json=data,
                params=params,
                timeout=30
            )
            if response.status_code in [200, 201, 204]:
                try:
                    response_data = response.json() if response.text else {}
                except json.JSONDecodeError:
                    response_data = {}
                return ApiResponse(success=True, data=response_data, status_code=response.status_code)
            else:
                error_msg = self._parse_error_response(response)
                return ApiResponse(success=False, error=error_msg, status_code=response.status_code)
        except requests.exceptions.ConnectionError:
            return ApiResponse(success=False, error="Cannot connect to API. Please ensure Docker container is running.")
        except requests.exceptions.Timeout:
            return ApiResponse(success=False, error="API request timed out.")
        except Exception as e:
            return ApiResponse(success=False, error=f"Unexpected error: {str(e)}")

    def _parse_error_response(self, response) -> str:
        try:
            error_data = response.json()
            if 'message' in error_data:
                return error_data['message']
            elif 'error' in error_data:
                return error_data['error']
        except:
            pass
        status_messages = {
            400: "Invalid request parameters",
            401: "Authentication failed - check your Bearer token",
            403: "Permission denied",
            404: "Resource not found",
            409: "Resource already exists",
            422: "Request cannot be processed",
            500: "API server error"
        }
        return status_messages.get(response.status_code, f"API error (status {response.status_code})")

    # Filesystem Entries
    def create_entry(self, filespace_id: str, parent_id: str, name: str) -> ApiResponse:
        """Create a directory entry in a filespace"""
        data = {"parentId": parent_id, "name": name, "type": "dir"}
        return self._make_request("POST", f"/filespaces/{filespace_id}/entries", data)

    def resolve_entry(self, filespace_id: str, path: str) -> ApiResponse:
        """Resolve a filesystem path to an entry"""
        return self._make_request("GET", f"/filespaces/{filespace_id}/entries/resolve", params={"path": path})

    def get_entry(self, filespace_id: str, entry_id: str) -> ApiResponse:
        """Get a filesystem entry by ID"""
        return self._make_request("GET", f"/filespaces/{filespace_id}/entries/{entry_id}")

    def delete_entry(self, filespace_id: str, entry_id: str) -> ApiResponse:
        """Delete a filesystem entry (must be empty directory)"""
        return self._make_request("DELETE", f"/filespaces/{filespace_id}/entries/{entry_id}")

    def list_entry_children(self, filespace_id: str, entry_id: str,
                             limit: Optional[int] = None, next_cursor: Optional[str] = None) -> ApiResponse:
        """List children of a directory entry"""
        params = {}
        if limit:
            params["limit"] = limit
        if next_cursor:
            params["nextCursor"] = next_cursor
        return self._make_request("GET", f"/filespaces/{filespace_id}/entries/{entry_id}/children",
                                  params=params or None)

    # External Data Stores
    def create_data_store(self, filespace_id: str, name: str, access_key: str,
                          secret_key: str, bucket_name: str, use_virtual_addressing: bool,
                          region: Optional[str] = None, endpoint: Optional[str] = None,
                          url_expiration_minutes: Optional[int] = None) -> ApiResponse:
        """Create an S3 external data store"""
        s3_params: Dict[str, Any] = {
            "accessKey": access_key,
            "secretKey": secret_key,
            "bucketName": bucket_name,
            "useVirtualAddressing": use_virtual_addressing,
        }
        if region:
            s3_params["region"] = region
        if endpoint:
            s3_params["endpoint"] = endpoint
        if url_expiration_minutes is not None:
            s3_params["urlExpirationMinutes"] = url_expiration_minutes
        data = {"name": name, "kind": "S3DataStore", "s3StorageParams": s3_params}
        return self._make_request("POST", f"/filespaces/{filespace_id}/external/data-stores", data)

    def list_data_stores(self, filespace_id: str, name: Optional[str] = None) -> ApiResponse:
        """List data stores for a filespace"""
        params = {}
        if name:
            params["name"] = name
        return self._make_request("GET", f"/filespaces/{filespace_id}/external/data-stores",
                                  params=params or None)

    def get_data_store(self, filespace_id: str, data_store_id: str) -> ApiResponse:
        """Get a specific data store by ID"""
        return self._make_request("GET", f"/filespaces/{filespace_id}/external/data-stores/{data_store_id}")

    def update_data_store(self, filespace_id: str, data_store_id: str,
                          access_key: str, secret_key: str) -> ApiResponse:
        """Update data store credentials"""
        data = {"s3StorageParams": {"accessKey": access_key, "secretKey": secret_key}}
        return self._make_request("PATCH", f"/filespaces/{filespace_id}/external/data-stores/{data_store_id}", data)

    def delete_data_store(self, filespace_id: str, data_store_id: str) -> ApiResponse:
        """Delete a data store"""
        return self._make_request("DELETE", f"/filespaces/{filespace_id}/external/data-stores/{data_store_id}")

    def ensure_folder_path(self, filespace_id: str, path: str) -> tuple[bool, Optional[str], str]:
        """Create all directories in path, returning (success, leaf_entry_id, error_message)"""
        parts = [p for p in path.strip("/").split("/") if p]
        current_path = ""
        current_id = None
        for folder in parts:
            current_path += f"/{folder}"
            success = False
            for attempt in range(3):
                result = self.resolve_entry(filespace_id, current_path)
                if result.success:
                    current_id = result.data.get("id") if result.data else None
                    if not current_id and isinstance(result.data, dict):
                        current_id = result.data.get("data", {}).get("id")
                    success = True
                    break
                create_result = self.create_entry(filespace_id, current_id, folder)
                if create_result.success:
                    current_id = create_result.data.get("id") if create_result.data else None
                    if not current_id and isinstance(create_result.data, dict):
                        current_id = create_result.data.get("data", {}).get("id")
                    success = True
                    break
                if create_result.status_code == 409:
                    time.sleep(0.2)
                    continue
                time.sleep(0.5)
            if not success:
                return False, None, f"Failed to create/resolve '{current_path}'"
        return True, current_id, ""

    # External Entries
    def create_external_entry(self, filespace_id: str, path: str,
                               data_store_id: str, object_id: str) -> ApiResponse:
        """Create an external entry backed by an S3 object"""
        data = {
            "path": path,
            "kind": "SingleObjectFile",
            "dataStoreId": data_store_id,
            "singleObjectFileParams": {"objectId": object_id},
        }
        return self._make_request("POST", f"/filespaces/{filespace_id}/external/entries", data)

    def list_external_entry_ids(self, filespace_id: str, data_store_id: str,
                                 limit: Optional[int] = None, next_cursor: Optional[str] = None) -> ApiResponse:
        """List external entry IDs for a data store"""
        params: Dict[str, Any] = {"dataStoreId": data_store_id}
        if limit:
            params["limit"] = limit
        if next_cursor:
            params["nextCursor"] = next_cursor
        return self._make_request("GET", f"/filespaces/{filespace_id}/external/entries/ids", params=params)

    def delete_external_entry(self, filespace_id: str, entry_id: str) -> ApiResponse:
        """Delete an external entry"""
        return self._make_request("DELETE", f"/filespaces/{filespace_id}/external/entries/{entry_id}")

    def get_service_health(self) -> ApiResponse:
        """Check API service health"""
        return self._make_request("GET", "/health")


