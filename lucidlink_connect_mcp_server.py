# Tool Implementation
@server.call_tool()
async def call_tool(name: str, arguments: dict):
    """Execute tool based on name and arguments"""
    global api_client

    try:
        # Docker Management Tools
        if name == "check_docker_status":
            installed = docker_mgr.is_docker_installed()
            running = docker_mgr.is_docker_running() if installed else False
            status = {"installed": installed, "running": running, "container_status": "unknown"}
            if not installed:
                status["message"] = "Docker Desktop is not installed. Please install from https://docker.com/products/docker-desktop"
            elif not running:
                if docker_mgr.start_docker():
                    status["running"] = True
                    status["message"] = "Docker Desktop started successfully"
                else:
                    status["message"] = "Failed to start Docker Desktop. Please start it manually."
            else:
                container, error = docker_mgr.ensure_container_running()
                if container:
                    status["container_status"] = container.status
                    status["message"] = "Docker and API container are ready"
                else:
                    status["container_status"] = "not_ready"
                    status["message"] = error or "Docker is running but API container failed to start"
            return [TextContent(type="text", text=json.dumps(status, indent=2))]

        elif name == "start_api_container":
            container, error = docker_mgr.ensure_container_running()
            if container:
                return [TextContent(type="text", text=format_success_message(
                    "API Container Started",
                    {"container_id": container.short_id, "status": container.status}
                ))]
            else:
                return [TextContent(type="text", text=format_error_message(
                    "Start API Container",
                    error or "Failed to start container. Check Docker Desktop."
                ))]

        elif name == "stop_api_container":
            success = docker_mgr.stop_container()
            if success:
                return [TextContent(type="text", text=format_success_message(
                    "API Container Stopped", {"status": "Container stopped successfully"}
                ))]
            else:
                return [TextContent(type="text", text=format_error_message(
                    "Stop API Container",
                    "Failed to stop container. It may not be running or Docker Desktop may not be running."
                ))]

        elif name == "view_container_logs":
            lines = arguments.get("lines", 50)
            logs = docker_mgr.get_container_logs(lines)
            return [TextContent(type="text", text=f"📜 Last {lines} lines of container logs:\n\n{logs}")]

        elif name == "pull_container_image":
            success, message = docker_mgr.pull_image(CONTAINER_IMAGE)
            if success:
                return [TextContent(type="text", text=format_success_message(
                    "Container Image Pulled",
                    {"image": CONTAINER_IMAGE, "message": message, "next_step": "You can now start the API container"}
                ))]
            else:
                return [TextContent(type="text", text=format_error_message("Pull Container Image", message))]

        elif name == "check_container_image":
            if docker_mgr.image_exists(CONTAINER_IMAGE):
                return [TextContent(type="text", text=format_success_message(
                    "Container Image Status",
                    {"image": CONTAINER_IMAGE, "status": "Available locally", "message": "Container image is ready to use"}
                ))]
            else:
                return [TextContent(
                    type="text",
                    text=f"⚠️ Container image '{CONTAINER_IMAGE}' not found locally.\n\n"
                         f"The image will be automatically pulled from Docker Hub when you start the container.\n\n"
                         f"Or you can pull it now by saying: 'Pull the container image'"
                )]

        elif name == "initialize_api":
            token = arguments.get("token") or get_bearer_token()
            if not token:
                return [TextContent(type="text", text=format_error_message(
                    "Initialize API",
                    "No bearer token provided. Please set LUCIDLINK_BEARER_TOKEN environment variable or provide token."
                ))]
            api_client = LucidLinkAPIClient(token)
            health = api_client.get_service_health()
            if health.success:
                return [TextContent(type="text", text=format_success_message(
                    "API Initialized", {"status": "Connected", "endpoint": API_BASE_URL}
                ))]
            else:
                return [TextContent(type="text", text=format_error_message(
                    "Initialize API", f"Failed to connect: {health.error}"
                ))]

        # Ensure API client is initialized for remaining tools
        if not api_client:
            token = get_bearer_token()
            if not token:
                return [TextContent(
                    type="text",
                    text="⚠️ API not initialized. Please provide your bearer token first using the initialize_api tool."
                )]
            api_client = LucidLinkAPIClient(token)

        # Ensure Docker and container are running
        if not docker_mgr.is_docker_running():
            docker_mgr.start_docker()
        container, error = docker_mgr.ensure_container_running()
        if not container:
            return [TextContent(type="text", text=format_error_message(
                "Container Setup",
                error or "Failed to start API container. Please check Docker status."
            ))]

        # Filesystem Entry tools
        if name == "create_entry":
            response = api_client.create_entry(
                arguments["filespace_id"], arguments["parent_id"], arguments["name"])
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    f"Created directory '{arguments['name']}'", response.data))]
            else:
                return [TextContent(type="text", text=format_error_message("Create Entry", response.error))]

        elif name == "resolve_entry":
            response = api_client.resolve_entry(arguments["filespace_id"], arguments["path"])
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    f"Resolved path '{arguments['path']}'", response.data))]
            else:
                return [TextContent(type="text", text=format_error_message("Resolve Entry", response.error))]

        elif name == "get_entry":
            response = api_client.get_entry(arguments["filespace_id"], arguments["entry_id"])
            if response.success:
                return [TextContent(type="text", text=format_success_message("Entry Details", response.data))]
            else:
                return [TextContent(type="text", text=format_error_message("Get Entry", response.error))]

        elif name == "delete_entry":
            if not arguments.get("confirm", False):
                return [TextContent(type="text", text="⚠️ Deletion not confirmed. Set confirm=true to proceed.")]
            response = api_client.delete_entry(arguments["filespace_id"], arguments["entry_id"])
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    "Deleted Entry", {"entry_id": arguments["entry_id"]}))]
            else:
                return [TextContent(type="text", text=format_error_message("Delete Entry", response.error))]

        elif name == "list_entry_children":
            response = api_client.list_entry_children(
                arguments["filespace_id"], arguments["entry_id"],
                limit=arguments.get("limit"), next_cursor=arguments.get("next_cursor"))
            if response.success:
                data = response.data if response.data else {}
                entries = data.get("data", {}).get("entries", []) if isinstance(data, dict) else []
                next_cur = data.get("data", {}).get("nextCursor") if isinstance(data, dict) else None
                if entries:
                    entry_list = "\n".join([
                        f"• [{e.get('type','?')}] {e.get('name','?')} (ID: {e.get('id','N/A')})"
                        for e in entries
                    ])
                    text = f"📂 {len(entries)} item(s):\n\n{entry_list}"
                    if next_cur:
                        text += f"\n\n🔄 More results available. Use next_cursor='{next_cur}' to continue."
                    return [TextContent(type="text", text=text)]
                else:
                    return [TextContent(type="text", text="📂 Directory is empty.")]
            else:
                return [TextContent(type="text", text=format_error_message("List Entry Children", response.error))]

        # External Data Store tools
        elif name == "create_data_store":
            response = api_client.create_data_store(
                filespace_id=arguments["filespace_id"],
                name=arguments["name"],
                access_key=arguments["access_key"],
                secret_key=arguments["secret_key"],
                bucket_name=arguments["bucket_name"],
                use_virtual_addressing=arguments["use_virtual_addressing"],
                region=arguments.get("region"),
                endpoint=arguments.get("endpoint"),
                url_expiration_minutes=arguments.get("url_expiration_minutes"),
            )
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    f"Created data store '{arguments['name']}'", response.data))]
            else:
                return [TextContent(type="text", text=format_error_message("Create Data Store", response.error))]

        elif name == "list_data_stores":
            response = api_client.list_data_stores(
                arguments["filespace_id"], name=arguments.get("name"))
            if response.success:
                data = response.data if response.data else {}
                stores = data.get("data", []) if isinstance(data, dict) else []
                if stores:
                    store_list = "\n".join([
                        f"• {s.get('name','Unknown')} (ID: {s.get('id','N/A')}, kind: {s.get('kind','N/A')})"
                        for s in stores
                    ])
                    return [TextContent(type="text", text=f"🗄️ {len(stores)} data store(s):\n\n{store_list}")]
                else:
                    return [TextContent(type="text", text="🗄️ No data stores found for this filespace.")]
            else:
                return [TextContent(type="text", text=format_error_message("List Data Stores", response.error))]

        elif name == "get_data_store":
            response = api_client.get_data_store(arguments["filespace_id"], arguments["data_store_id"])
            if response.success:
                return [TextContent(type="text", text=format_success_message("Data Store Details", response.data))]
            else:
                return [TextContent(type="text", text=format_error_message("Get Data Store", response.error))]

        elif name == "update_data_store":
            response = api_client.update_data_store(
                arguments["filespace_id"], arguments["data_store_id"],
                arguments["access_key"], arguments["secret_key"])
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    "Updated Data Store Credentials", response.data))]
            else:
                return [TextContent(type="text", text=format_error_message("Update Data Store", response.error))]

        elif name == "delete_data_store":
            if not arguments.get("confirm", False):
                return [TextContent(type="text", text="⚠️ Deletion not confirmed. Set confirm=true to proceed.")]
            response = api_client.delete_data_store(arguments["filespace_id"], arguments["data_store_id"])
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    "Deleted Data Store", {"data_store_id": arguments["data_store_id"]}))]
            else:
                return [TextContent(type="text", text=format_error_message("Delete Data Store", response.error))]

        # External Entry tools
        elif name == "create_external_entry":
            response = api_client.create_external_entry(
                filespace_id=arguments["filespace_id"],
                path=arguments["path"],
                data_store_id=arguments["data_store_id"],
                object_id=arguments["object_id"],
            )
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    f"Created external entry at '{arguments['path']}'", response.data))]
            else:
                return [TextContent(type="text", text=format_error_message("Create External Entry", response.error))]

        elif name == "list_external_entry_ids":
            response = api_client.list_external_entry_ids(
                arguments["filespace_id"], arguments["data_store_id"],
                limit=arguments.get("limit"), next_cursor=arguments.get("next_cursor"))
            if response.success:
                data = response.data if response.data else {}
                ids = data.get("data", {}).get("ids", []) if isinstance(data, dict) else []
                next_cur = data.get("data", {}).get("nextCursor") if isinstance(data, dict) else None
                text = f"🔗 {len(ids)} external entry ID(s):\n\n" + "\n".join(f"• {eid}" for eid in ids)
                if next_cur:
                    text += f"\n\n🔄 More available. Use next_cursor='{next_cur}' to continue."
                return [TextContent(type="text", text=text if ids else "🔗 No external entries found.")]
            else:
                return [TextContent(type="text", text=format_error_message("List External Entry IDs", response.error))]

        elif name == "delete_external_entry":
            if not arguments.get("confirm", False):
                return [TextContent(type="text", text="⚠️ Deletion not confirmed. Set confirm=true to proceed.")]
            response = api_client.delete_external_entry(arguments["filespace_id"], arguments["entry_id"])
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    "Deleted External Entry", {"entry_id": arguments["entry_id"]}))]
            else:
                return [TextContent(type="text", text=format_error_message("Delete External Entry", response.error))]

        # High-Level Workflow Tools
        elif name == "ensure_folder_path":
            filespace_id = arguments["filespace_id"]
            path = arguments["path"]
            success, leaf_id, error = api_client.ensure_folder_path(filespace_id, path)
            if success:
                return [TextContent(type="text", text=format_success_message(
                    f"Ensured folder path '{path}'",
                    {"path": path, "leaf_entry_id": leaf_id}
                ))]
            else:
                return [TextContent(type="text", text=format_error_message("Ensure Folder Path", error))]

        elif name == "import_s3_object":
            filespace_id = arguments["filespace_id"]
            data_store_id = arguments["data_store_id"]
            s3_key = arguments["s3_key"]
            ll_path = arguments["ll_path"]
            # Ensure parent directory exists
            path_parts = ll_path.strip("/").split("/")
            dir_path = "/" + "/".join(path_parts[:-1]) if len(path_parts) > 1 else ""
            if dir_path and dir_path != "/":
                success, _, error = api_client.ensure_folder_path(filespace_id, dir_path)
                if not success:
                    return [TextContent(type="text", text=format_error_message(
                        "Import S3 Object", f"Failed to create directory '{dir_path}': {error}"))]
            response = api_client.create_external_entry(filespace_id, ll_path, data_store_id, s3_key)
            if response.success:
                return [TextContent(type="text", text=format_success_message(
                    f"Imported S3 object '{s3_key}' → '{ll_path}'", response.data))]
            else:
                return [TextContent(type="text", text=format_error_message("Import S3 Object", response.error))]

        elif name == "bulk_import_s3_objects":
            filespace_id = arguments["filespace_id"]
            data_store_id = arguments["data_store_id"]
            objects = arguments["objects"]
            stop_on_error = arguments.get("stop_on_error", False)
            # Collect unique directories
            dirs = set()
            for obj in objects:
                ll_path = obj["ll_path"]
                parts = ll_path.strip("/").split("/")
                if len(parts) > 1:
                    dirs.add("/" + "/".join(parts[:-1]))
            # Ensure directories (sorted so parents before children)
            dir_failures = []
            for dir_path in sorted(dirs):
                success, _, error = api_client.ensure_folder_path(filespace_id, dir_path)
                if not success:
                    dir_failures.append({"dir": dir_path, "error": error})
                    if stop_on_error:
                        return [TextContent(type="text", text=format_error_message(
                            "Bulk Import", f"Directory creation failed for '{dir_path}': {error}"))]
            # Link each object
            succeeded, failed, failures = 0, 0, []
            for obj in objects:
                s3_key = obj["s3_key"]
                ll_path = obj["ll_path"]
                response = api_client.create_external_entry(filespace_id, ll_path, data_store_id, s3_key)
                if response.success:
                    succeeded += 1
                else:
                    failed += 1
                    failures.append({"s3_key": s3_key, "ll_path": ll_path, "error": response.error})
                    if stop_on_error:
                        break
            summary = {
                "total": len(objects),
                "succeeded": succeeded,
                "failed": failed,
                "dir_failures": dir_failures,
                "object_failures": failures
            }
            if failed == 0 and not dir_failures:
                return [TextContent(type="text", text=format_success_message(
                    f"Bulk Import: {succeeded}/{len(objects)} objects imported", summary))]
            else:
                msg = f"Bulk Import completed with errors: {succeeded} succeeded, {failed} failed"
                return [TextContent(type="text", text=f"⚠️ {msg}\n\n{json.dumps(summary, indent=2)}")]

        elif name == "get_connect_workflow_guide":
            return [TextContent(type="text", text=CONNECT_WORKFLOW_GUIDE)]

        elif name == "generate_connect_ui":
            filespace_id = arguments.get("filespace_id", "")
            data_store_id = arguments.get("data_store_id", "")
            html = CONNECT_UI_TEMPLATE.replace("{FILESPACE_ID}", filespace_id).replace("{DATA_STORE_ID}", data_store_id)
            return [TextContent(type="text", text=html)]

        else:
            return [TextContent(type="text", text=f"❌ Unknown tool: {name}")]

    except Exception as e:
        logger.error(f"Tool execution error: {e}", exc_info=True)
        return [TextContent(
            type="text",
            text=f"❌ Unexpected error: {str(e)}\n\nPlease check the logs for more details."
        )]


